def generate_kyc_review(case_data: dict) -> dict:
    """
    Generate a structured KYC review from a validated KYC case.

    This is a deterministic first version.
    Later, this structure will be generated by the LLM.
    """

    expected_volume = case_data["expected_transaction_volume"]["monthly_volume_chf"]
    actual_volume = case_data["actual_transaction_summary"]["monthly_volume_chf"]

    key_risk_indicators = []

    if actual_volume > expected_volume:
        key_risk_indicators.append(
            "Actual transaction volume exceeds expected transaction volume."
        )

    if case_data["ubo_information"]["ownership_percentage"] >= 50:
        key_risk_indicators.append(
            "Customer has a majority UBO ownership structure."
        )

    if case_data["risk_rating"] == "High":
        key_risk_indicators.append(
            "Customer is already classified as high risk."
        )

    if case_data["adverse_media_summary"] != "No confirmed adverse media identified in the synthetic case.":
        key_risk_indicators.append(
            "Potential adverse media information requires review."
        )

    human_review_required = len(key_risk_indicators) > 0

    if human_review_required:
        recommended_action = "Review required"
    else:
        recommended_action = "No immediate risk escalation required"

    review = {
        "customer_id": case_data["customer_id"],
        "customer_name": case_data["customer_name"],
        "risk_summary": (
            f"The customer is a {case_data['customer_type']} based in "
            f"{case_data['country']} with a current risk rating of "
            f"{case_data['risk_rating']}."
        ),
        "key_risk_indicators": key_risk_indicators,
        "missing_information": case_data["missing_information"],
        "recommended_action": recommended_action,
        "rationale": (
            "The review is based on declared activity, expected transaction "
            "volume, actual transaction behaviour, UBO information and adverse "
            "media summary."
        ),
        "human_review_required": human_review_required,
    }

    return review